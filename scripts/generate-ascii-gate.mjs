import { writeFile } from "node:fs/promises";
import path from "node:path";
import process from "node:process";
import sharp from "sharp";

const columns = 270;
const rows = 105;
const characterRamp = " .,:;-+=*#%@";
const sourcePath = path.join(
  process.cwd(),
  "public",
  "ascii-background-light.png",
);
const outputPath = path.join(
  process.cwd(),
  "src",
  "app",
  "components",
  "asciiGateData.ts",
);

const { data } = await sharp(sourcePath)
  .flatten({ background: "#ffffff" })
  .resize(columns, rows, { fit: "fill", kernel: sharp.kernel.lanczos3 })
  .greyscale()
  .raw()
  .toBuffer({ resolveWithObject: true });

const asciiRows = [];

for (let row = 0; row < rows; row += 1) {
  let line = "";

  for (let column = 0; column < columns; column += 1) {
    const darkness = 1 - data[row * columns + column] / 255;

    if (darkness < 0.012) {
      line += " ";
      continue;
    }

    const normalized = Math.min(1, (darkness - 0.012) / 0.58);
    const rampIndex = Math.min(
      characterRamp.length - 1,
      Math.floor(Math.pow(normalized, 0.38) * characterRamp.length),
    );
    line += characterRamp[rampIndex];
  }

  asciiRows.push(line.trimEnd());
}

const output =
  "// Generated by scripts/generate-ascii-gate.mjs.\n" +
  `export const ASCII_GATE_COLUMNS = ${columns};\n` +
  `export const ASCII_GATE_ROWS = ${rows};\n` +
  `export const ASCII_GATE = String.raw\`${asciiRows.join("\n")}\`;\n`;

await writeFile(outputPath, output);
